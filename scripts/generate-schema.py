"""Generate the new-install MySQL init SQL from the same schema exercised by the API.

Run from the repository root: PYTHONPATH=fastapi python scripts/generate-schema.py
"""
from pathlib import Path

from sqlalchemy.dialects.mysql import dialect
from sqlalchemy.schema import CreateIndex, CreateTable

from app.db import metadata, sessions

root = Path(__file__).resolve().parents[1]


def ddl(tables):
    statements = []
    for table in tables:
        statements.append(str(CreateTable(table).compile(dialect=dialect())).strip() + ";")
        statements.extend(str(CreateIndex(index).compile(dialect=dialect())) + ";"
                          for index in sorted(table.indexes, key=lambda index: index.name))
    return "\n".join(line.rstrip() for line in "\n\n".join(statements).splitlines()) + "\n"


init = root / "mysql/init/001-schema.sql"
init.parent.mkdir(parents=True, exist_ok=True)
init.write_text("-- Generated by scripts/generate-schema.py; edit app/db.py, then regenerate.\n"
                "-- MYSQL_DATABASE selects the target database before this script runs.\n"
                "SET NAMES utf8mb4;\n\n" + ddl(metadata.sorted_tables)
                + "\nINSERT INTO villa_schedule_lock(id) VALUES (1);\n", encoding="utf-8", newline="\n")
upgrade = root / "mysql/upgrade/001-fastapi-sessions.sql"
upgrade.parent.mkdir(parents=True, exist_ok=True)
upgrade.write_text("-- Apply ONCE to an existing MySQL database migrated through Spring Flyway V5.\n"
                   + ddl([sessions]), encoding="utf-8", newline="\n")
